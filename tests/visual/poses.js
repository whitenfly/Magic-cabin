/**
 * ⚠️ 已知观感（**不是渲染缺失，不要重复排查**）
 * ============================================================================
 * 二楼机位画面右侧是 `x = +4` 的叠木墙。线稿风格下墙体 = 「白色填充 + 每根原木一圈描边」，
 * 原木直径 0.3m，在 3.8m 距离处占屏幕约 76px —— 于是墙看起来是**一大片白**，只有几条细线。
 *
 * 这曾引起一次误判（"右侧墙面没渲染出来"）。实测证据（`full` 模式）：
 *
 * | 测法 | 结果 |
 * |---|---|
 * | 正对右墙 x=+4（full） | 边缘 5.96%，深色描边像素 0.763% |
 * | 正对左墙 x=-4（full，常驻墙，作对照） | 边缘 5.45%，深色描边像素 0.780% |
 * | 画面最深像素值 | 13–16（即 `MAT` 的 `0x111111`）—— **描边确实画出来了** |
 *
 * 右墙与左墙的数据几乎相同 ⇒ 四面墙渲染一致。真正的坑在**统计指标**：
 * 只按水平差分算边缘，会漏掉叠木墙的**横向木纹**，把"有木纹的白墙"统计成"空白"。
 * `png.mjs` 的 `analyzeImage()` 已改为同时看水平与垂直差分，别再改回去。
 *
 * 调试时若怀疑"某块没渲染"，用 `node tests/visual/view.mjs <png> --mode=edge` 看线条分布，
 * 直接数像素比肉眼可靠。
 */

/** J0.4 回归默认使用的机位顺序（与 `baseline/manifest.json` 的 `poses` 一致） */
export const DEFAULT_POSE_ORDER = ['default-fixed', 'floor1-indoor', 'floor2-desk']

/** 把 cam 数组转成页面 URL 参数形式（`a,b,c,d,e,f`） */
export function camParam(cam) {
  return cam ? cam.join(',') : ''
}

/** 按名字取机位；未知名字返回 null（由调用方决定报错还是忽略） */
export function resolvePose(name) {
  if (!name) return null
  return Object.prototype.hasOwnProperty.call(POSES, name) ? POSES[name] : null
}
