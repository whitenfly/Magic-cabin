/**
 * J0.4 · 截图回归机位表（**测试资产**）
 * ============================================================================
 * 为什么机位表在 `tests/` 而不是 `src/cabin/`：
 *
 * - 机位是**观测条件**，属于"判据"的一部分，与 `baseline/` 同住一个目录才不容易漂移；
 * - `src/cabin/**` 里出现具体世界坐标会违反架构不变量 `N9`（坐标系数字只能来自
 *   `cabin/world/layout.js`，交互判定与几何构建共用同一常量）——
 *   产品代码不该为了测试而携带一组固定的观察点。
 *
 * 因此数据流是**单向**的：本文件 → 拼出 `?cam=` URL → 页面按参数覆盖相机。
 * 页面侧只认识"六个数"，不认识"机位名"。
 *
 * ## 机位的表达
 *
 *     cam: [px, py, pz, lx, ly, lz]   // 相机位置 → 注视点（世界坐标）
 *
 * 为什么不写成「玩家位置 + 视角模式」：那会引入重力、碰撞、平台判定一整套游戏逻辑，
 * 画面会随落点是否卡进家具而变。相机位是**纯观察量**，与玩法无关 ——
 * 在 `J2`（`CameraRig`）与 `J3`/`J4`（物件与系统搬迁）重写相机之前，它是最稳的观测锚点。
 *
 * `cam: null` 表示**不做任何覆盖**：这份画面就是玩家打开页面看到的默认固定视角，
 * 也是"改动前 vs 改动后"最直接的对照。
 *
 * ## 坐标来源（可追溯）
 *
 * 取值自 `src/cabin/legacy/monolith.js` 的场景常量（`J2.9` 会把它们集中到
 * `src/cabin/world/layout.js`，届时本文件的注释需同步指向那里）：
 *
 * | 常量 | 值 | 位置 |
 * |---|---|---|
 * | `FLOOR_TOP`（二楼地板高度） | `3.12` | L255 |
 * | `TBLX / TBLZ`（二楼书桌中心） | `2.5 / -2.5` | L2583 |
 * | 室内净空 | 内墙约 `±4.2`，中央螺旋楼梯半径约 `1.2` | L7384–L7400 |
 *
 * ⚠️ **改动任何一个坐标都会让基线失效** —— 必须重新生成基线并**人工审查画面**
 * （`node tests/visual/capture.mjs --update`），不要改完数字就忽略差异。
 *
 * ## 用法
 *
 * ```bash
 * node tests/visual/capture.mjs                    # 抓全部机位
 * node tests/visual/compare.mjs                    # 与基线比对
 * # 手工探索某个机位（页面 URL 里的六个数就是 cam）：
 * #   http://127.0.0.1:5173/index.html?deterministic=1&frames=120&cam=0,1.55,3,-1.6,1.1,-1.2
 * ```
 */

